"""OR-12: 2-D time-harmonic cross-section of one 0.8 x 0.07 mm D09 trace in a uniform field, gmsh + GetDP (Agent 4).

Usage (with numpy, gmsh and getdp on PATH):
    /home/claude/fea/venv/bin/python -I or12.py --out results/or12 --reference results/embodic_reference.json

Case: engineering_verification_plan.md section 2, OR-12. The trace is centred at the origin, width w along x, thickness
t along y, in a square air box. A_z = A_ext on the box edge: 12a (B_z, normal to the wide face) A_ext = -B0 x, so
B_y = B0; 12b (B_t, along the wide face) A_ext = B0 y, so B_x = B0. The copper carries J = -j omega sigma A. With the
trace and the boundary data both odd about the centre, A is odd and the net current is zero without a scalar
potential; the script prints the net current to show it. Loss per metre = int sigma omega^2 |A|^2 / 2 over the trace.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import math
import os
import re
import subprocess
import time
from pathlib import Path

W_MM, T_MM = 0.8, 0.07  # D09 Table 2
F_E = 8 * 2000 / 60  # D09 Table 2, 266.67 Hz
B0 = 0.846122  # T, example level (D09 A b1); the loss scales with B0^2
MU0 = 4e-7 * math.pi


@dataclasses.dataclass(frozen=True)
class Case:
    """One OR-12 run: field direction, frequency multiple, copper mesh level, air box, conductor on or off."""

    label: str
    field: str  # "Bz" (normal to the wide face) or "Bt" (along the wide face)
    freq_mult: float
    level: int  # copper element size t/4 / 2**level
    box_mm: float = 24.0
    conductor: bool = True
    width_mm: float = W_MM

    @property
    def h_cu_mm(self) -> float:
        """Element size in the copper."""
        return T_MM / 4 / 2**self.level


def geo_text(c: Case) -> str:
    """Return the gmsh .geo in metres: the trace rectangle inside a square air box."""
    w, t, b, h = c.width_mm * 1e-3 / 2, T_MM * 1e-3 / 2, c.box_mm * 1e-3 / 2, c.h_cu_mm * 1e-3
    hb = c.box_mm * 1e-3 / 40
    return f"""// OR-12 {c.label}, generated by or12.py
Point(1) = {{{-w!r}, {-t!r}, 0, {h!r}}}; Point(2) = {{{w!r}, {-t!r}, 0, {h!r}}};
Point(3) = {{{w!r}, {t!r}, 0, {h!r}}}; Point(4) = {{{-w!r}, {t!r}, 0, {h!r}}};
Point(5) = {{{-b!r}, {-b!r}, 0, {hb!r}}}; Point(6) = {{{b!r}, {-b!r}, 0, {hb!r}}};
Point(7) = {{{b!r}, {b!r}, 0, {hb!r}}}; Point(8) = {{{-b!r}, {b!r}, 0, {hb!r}}};
Line(1) = {{1, 2}}; Line(2) = {{2, 3}}; Line(3) = {{3, 4}}; Line(4) = {{4, 1}};
Line(5) = {{5, 6}}; Line(6) = {{6, 7}}; Line(7) = {{7, 8}}; Line(8) = {{8, 5}};
Curve Loop(1) = {{1, 2, 3, 4}}; Curve Loop(2) = {{5, 6, 7, 8}};
Plane Surface(1) = {{1}}; Plane Surface(2) = {{2, 1}};
Mesh.MeshSizeExtendFromBoundary = 1;
Physical Surface("copper", 1) = {{1}};
Physical Surface("air", 2) = {{2}};
Physical Curve("outer", 10) = {{5, 6, 7, 8}};
"""


def pro_text(c: Case) -> str:
    """Return the GetDP problem: complex A_z, J = -j omega sigma A in the copper, A_ext on the box edge."""
    aext = f"-{B0!r}*X[]" if c.field == "Bz" else f"{B0!r}*Y[]"
    sigma = 1 / 1.7241e-8 if c.conductor else 0.0
    return f"""// OR-12 {c.label}, generated by or12.py
Group {{ Cu = Region[1]; Air = Region[2]; Outer = Region[10]; Domain = Region[{{Cu, Air}}]; }}
Function {{
  mu0 = 4e-7*Pi; nu[] = 1/mu0;
  sigma[Cu] = {sigma!r};
  Freq = {F_E * c.freq_mult!r};
  aext[] = {aext};
}}
Constraint {{ {{ Name a_bc; Case {{ {{ Region Outer; Value aext[]; }} }} }} }}
Jacobian {{ {{ Name Vol; Case {{ {{ Region All; Jacobian Vol; }} }} }} }}
Integration {{ {{ Name Int; Case {{ {{ Type Gauss; Case {{ {{ GeoElement Triangle; NumberOfPoints 6; }} }} }} }} }} }}
FunctionSpace {{
  {{ Name Hcurl_a; Type Form1P;
    BasisFunction {{ {{ Name se; NameOfCoef ae; Function BF_PerpendicularEdge;
      Support Domain; Entity NodesOf[All]; }} }}
    Constraint {{ {{ NameOfCoef ae; EntityType NodesOf; NameOfConstraint a_bc; }} }}
  }}
}}
Formulation {{
  {{ Name MagDyn_a; Type FemEquation;
    Quantity {{ {{ Name a; Type Local; NameOfSpace Hcurl_a; }} }}
    Equation {{
      Galerkin {{ [ nu[] * Dof{{d a}}, {{d a}} ]; In Domain; Jacobian Vol; Integration Int; }}
      Galerkin {{ DtDof [ sigma[] * Dof{{a}}, {{a}} ]; In Cu; Jacobian Vol; Integration Int; }}
    }}
  }}
}}
Resolution {{
  {{ Name MagDyn_a;
    System {{ {{ Name A; NameOfFormulation MagDyn_a; Type Complex; Frequency Freq; }} }}
    Operation {{ Generate[A]; Solve[A]; SaveSolution[A]; }} }}
}}
PostProcessing {{
  {{ Name MagDyn_a; NameOfFormulation MagDyn_a;
    Quantity {{
      {{ Name b; Value {{ Term {{ [ {{d a}} ]; In Domain; Jacobian Vol; }} }} }}
      {{ Name loss; Value {{ Integral {{ [ 0.5 * sigma[] * SquNorm[Dt[{{a}}]] ];
        In Cu; Jacobian Vol; Integration Int; }} }} }}
      {{ Name inet; Value {{ Integral {{ [ -sigma[] * Dt[CompZ[{{a}}]] ];
        In Cu; Jacobian Vol; Integration Int; }} }} }}
      {{ Name iabs; Value {{ Integral {{ [ Norm[sigma[] * Dt[CompZ[{{a}}]]] ];
        In Cu; Jacobian Vol; Integration Int; }} }} }}
    }}
  }}
}}
PostOperation {{
  {{ Name Out; NameOfPostProcessing MagDyn_a;
    Operation {{
      Print[ loss[Cu], OnGlobal, Format Table, File "loss.txt" ];
      Print[ inet[Cu], OnGlobal, Format Table, File "inet.txt" ];
      Print[ iabs[Cu], OnGlobal, Format Table, File "iabs.txt" ];
      Print[ b, OnPoint {{0, 0, 0}}, Format Table, File "b_centre.txt" ];
      Print[ b, OnPoint {{{c.width_mm * 1e-3 / 4!r}, {T_MM * 1e-3 / 4!r}, 0}}, Format Table, File "b_off.txt" ];
    }}
  }}
}}
"""


def numbers(path: Path) -> list[float]:
    """Return every number of a GetDP Table output file."""
    return [float(v) for v in re.split(r"\s+", path.read_text().strip())]


def run(cmd: list[str], cwd: Path, log: Path) -> float:
    """Run one tool at low priority, append its output to the solver log, stop on a non-zero exit."""
    env = dict(os.environ, OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1")
    t0 = time.perf_counter()
    proc = subprocess.run(["nice", "-n", "10", *cmd], cwd=cwd, env=env, capture_output=True, text=True)
    dt = time.perf_counter() - t0
    with log.open("a") as fh:
        fh.write(f"$ {' '.join(cmd)}\n{proc.stdout}{proc.stderr}exit {proc.returncode}, {dt:.2f} s\n\n")
    if proc.returncode != 0:
        raise SystemExit(f"{cmd[0]} failed in {cwd}, see {log}")
    return dt


def solve(c: Case, root: Path) -> dict:
    """Mesh and solve one case in root/label; return the loss per metre and the field checks."""
    work = root / c.label
    work.mkdir(parents=True, exist_ok=True)
    log = work / "solver_log.txt"
    log.write_text("")
    (work / "or12.geo").write_text(geo_text(c))
    (work / "or12.pro").write_text(pro_text(c))
    run(["gmsh", "-2", "-nt", "1", "-format", "msh2", "or12.geo", "-o", "or12.msh"], work, log)
    t_solve = run(["getdp", "or12.pro", "-msh", "or12.msh", "-solve", "MagDyn_a", "-pos", "Out", "-v", "3"], work, log)
    text = (work / "or12.msh").read_text()
    nodes = int(text.split("$Nodes\n", 1)[1].split("\n", 1)[0])
    loss = numbers(work / "loss.txt")  # region, re, im
    inet = numbers(work / "inet.txt")
    iabs = numbers(work / "iabs.txt")
    bc = numbers(work / "b_centre.txt")[-6:]  # re bx by bz, im bx by bz
    bo = numbers(work / "b_off.txt")[-6:]
    return {
        "case": dataclasses.asdict(c),
        "h_cu_mm": c.h_cu_mm,
        "nodes": nodes,
        "t_solve_s": t_solve,
        "loss_w_per_m": loss[1],
        "net_current_over_abs": math.hypot(inet[1], inet[2]) / iabs[1] if iabs[1] > 0 else 0.0,
        "b_centre_re_xy": bc[:2],
        "b_centre_im_xy": bc[3:5],
        "b_off_re_xy": bo[:2],
    }


def rel(x: float, ref: float) -> float:
    """Return x / ref - 1."""
    return x / ref - 1.0


def main() -> int:
    """Run the OR-12 cases and write the JSON and the Markdown tables."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--reference", type=Path, required=True)
    args = ap.parse_args()
    root = args.out.resolve()
    ref = json.loads(args.reference.read_text())["or12"]
    rho = ref["rho_ohm_m"]
    sigma = 1 / rho
    assert abs(rho - 1.7241e-8) < 1e-20, rho

    def emb(field: str, mult: int) -> float:
        name = {"Bz": "12a_Bz", "Bt": "12b_Bt"}[field]
        return next(
            r["loss_w_per_m"] for r in ref["rows"] if r["case"] == name and abs(r["frequency_hz"] - F_E * mult) < 1e-6
        )

    cases = [
        Case(f"{fld}_f{m}_L{lv}", fld, m, lv)
        for fld, m in (("Bz", 1), ("Bt", 1), ("Bz", 13), ("Bt", 13))
        for lv in (0, 1, 2)
    ]
    cases += [Case("Bz_f1_L2_box48", "Bz", 1, 2, box_mm=48.0), Case("Bt_f1_L2_box48", "Bt", 1, 2, box_mm=48.0)]
    cases += [Case("Bz_f1_L1_noCu", "Bz", 1, 1, conductor=False), Case("Bt_f1_L1_noCu", "Bt", 1, 1, conductor=False)]
    delta1 = math.sqrt(rho / (math.pi * F_E * MU0))
    slab_mult = (delta1 / (T_MM * 1e-3 / 2)) ** 2  # t / delta = 2
    cases += [Case(f"Bt_slab_L{lv}", "Bt", slab_mult, lv) for lv in (0, 1, 2)]
    cases += [Case("Bt_slab_w8_L2", "Bt", slab_mult, 2, box_mm=240.0, width_mm=8.0)]
    res = {}
    for c in cases:
        res[c.label] = solve(c, root)
        print(
            f"{c.label}: nodes {res[c.label]['nodes']}, loss {res[c.label]['loss_w_per_m']:.6e} W/m,"
            f" net/abs current {res[c.label]['net_current_over_abs']:.1e}, b0 {res[c.label]['b_centre_re_xy']}",
            flush=True,
        )
    (root / "or12_results.json").write_text(json.dumps(res, indent=1))

    md = ["# OR-12 tables (generated by or12.py)", ""]
    for m in (1, 13):
        f = F_E * m
        delta = math.sqrt(rho / (math.pi * f * MU0)) * 1e3
        md += [
            f"## {f:.2f} Hz: skin depth {delta:.4f} mm, w/delta {W_MM / delta:.4f}, t/delta {T_MM / delta:.4f}",
            "",
            "| case | level | copper h mm | nodes | FEA W/m | change | embodic W/m | FEA / embodic - 1 |"
            " net I / int abs J |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for fld in ("Bz", "Bt"):
            prev = None
            for lv in (0, 1, 2):
                r = res[f"{fld}_f{m}_L{lv}"]
                ch = f"{rel(r['loss_w_per_m'], prev) * 100:+.3f} %" if prev else "-"
                e = emb(fld, m)
                md.append(
                    f"| {fld} | {lv} | {r['h_cu_mm']:.6f} | {r['nodes']} | {r['loss_w_per_m']:.6e} | {ch} | {e:.6e} |"
                    f" {rel(r['loss_w_per_m'], e):+.2e} | {r['net_current_over_abs']:.1e} |"
                )
                prev = r["loss_w_per_m"]
        md.append("")
    md += ["## Assumption checks at 266.67 Hz", "", "| run | value | against | rel |", "|---|---|---|---|"]
    for fld in ("Bz", "Bt"):
        a, b = res[f"{fld}_f1_L2_box48"]["loss_w_per_m"], res[f"{fld}_f1_L2"]["loss_w_per_m"]
        md.append(f"| {fld} box 48 mm, level 2 | {a:.6e} W/m | box 24 mm {b:.6e} W/m | {rel(a, b) * 100:+.4f} % |")
        bx, by = res[f"{fld}_f1_L1_noCu"]["b_centre_re_xy"]
        comp = by if fld == "Bz" else bx
        md.append(
            f"| {fld} no conductor, B at the trace centre | {comp:.6f} T | B0 {B0} T | {rel(comp, B0) * 100:+.4f} % |"
        )
    for fld, form, closed in (
        (
            "Bz",
            "sigma w^2 B0^2 w^3 t / 24",
            sigma * (2 * math.pi * F_E) ** 2 * B0**2 * (W_MM * 1e-3) ** 3 * T_MM * 1e-3 / 24,
        ),
        (
            "Bt",
            "sigma w^2 B0^2 w t^3 / 24",
            sigma * (2 * math.pi * F_E) ** 2 * B0**2 * W_MM * 1e-3 * (T_MM * 1e-3) ** 3 / 24,
        ),
    ):
        md.append(
            f"| own closed form {fld}, {form} | {closed:.6e} W/m | embodic {emb(fld, 1):.6e} W/m |"
            f" {rel(closed, emb(fld, 1)):.1e} |"
        )
    r = res["Bt_slab_L2"]
    f = F_E * slab_mult
    omega, delta = 2 * math.pi * f, math.sqrt(rho / (math.pi * f * MU0))
    xi = T_MM * 1e-3 / delta
    h0 = B0 / MU0
    slab = h0**2 / (sigma * delta) * (math.sinh(xi) - math.sin(xi)) / (math.cosh(xi) + math.cos(xi)) * W_MM * 1e-3
    low = sigma * omega**2 * B0**2 * W_MM * 1e-3 * (T_MM * 1e-3) ** 3 / 24
    md += [
        "",
        f"## Instrument check: B_t at {f:.4g} Hz, t/delta {xi:.3f} (skin effect strong)",
        "",
        "| quantity | W/m | FEA / it - 1 |",
        "|---|---|---|",
        *(f"| FEA, level {lv} | {res[f'Bt_slab_L{lv}']['loss_w_per_m']:.6e} | - |" for lv in (0, 1, 2)),
        f"| exact 1-D slab (H0^2/(sigma delta)) (sinh xi - sin xi)/(cosh xi + cos xi) x w | {slab:.6e} |"
        f" {rel(r['loss_w_per_m'], slab) * 100:+.2f} % |",
        f"| EQ-12 low-frequency form sigma w^2 B0^2 w t^3 / 24 | {low:.6e} |"
        f" {rel(r['loss_w_per_m'], low) * 100:+.2f} % |",
    ]
    r8 = res["Bt_slab_w8_L2"]["loss_w_per_m"]
    md.append(
        f"| FEA, 8 mm wide strip, box 240 mm, per mm of width x 0.8 mm | {r8 / 10:.6e} |"
        f" slab {rel(r8 / 10, slab) * 100:+.2f} % |"
    )
    (root / "or12_tables.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
