"""V3-01 re-ruling of release 0.0.4 (U-V18): pin, check and record the rulings of v3_01_rulings_v18.py.

    python3 tests/independent/m7/v18_rerule.py --pin      # writes records/V3-01_pins_c25d8a9.json
    python3 tests/independent/m7/v18_rerule.py --check    # every cite ran, carried the marker and passed in 0.0.4
    python3 tests/independent/m7/v18_rerule.py --write    # writes records/V3-01_0.0.4.md

The test sources are `git archive c25d8a9 tests`; the reports and the gate log are the gzipped inputs of
req_audit.py --target 0.0.4, merged as that script merges them. The pins hash what req_audit.py hashes
(`cite_hash`), so the audit sees the same values.
"""

import argparse
import importlib.util
import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
RECORD = HERE / "records/V3-01_0.0.4.md"


def load(path: Path):
    """Import a module by path."""
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


AUDIT = load(REPO / "docs/phase3/verification/checks/req_audit.py")
V18 = load(HERE / "v3_01_rulings_v18.py")
TARGET = AUDIT.TARGETS["0.0.4"]


def pins(tree: Path) -> dict[str, dict[str, str]]:
    """Return {req: {cite: sha256}} of every non-gate cite of a `checks` ruling, on the c25d8a9 tests."""
    return {
        req: {c: AUDIT.cite_hash(c, tree) for c in r.cites if not c.startswith("gate:")}
        for req, r in sorted(V18.RULINGS.items())
        if r.ruling == "checks"
    }


def problems() -> list[str]:
    """Return one line per cite that did not run, lacks the row's marker or did not pass, or a gate without PASS."""
    report = AUDIT.read_reports(TARGET.reports)
    gates = AUDIT.gate_ids(AUDIT.read_bytes(TARGET.gate_log).decode("utf-8"))
    out = []
    for req, ruling in sorted(V18.RULINGS.items()):
        for cite in ruling.cites:
            if cite.startswith("gate:"):
                if cite.removeprefix("gate:") not in gates:
                    out.append(f"{req}: no PASS line for {cite}")
                continue
            if cite.startswith("record:"):
                continue
            runs = [r for r in report if r["nodeid"].split("[")[0] == cite]
            if not runs:
                out.append(f"{req}: not in the report: {cite}")
            elif any(req not in r["req"] for r in runs) or {r["outcome"] for r in runs} != {"passed"}:
                outcomes, markers = {r["outcome"] for r in runs}, {x for r in runs for x in r["req"]}
                out.append(f"{req}: {cite} ran {sorted(outcomes)} with markers {sorted(markers)}")
    return out


def render(changed_rows: str) -> str:
    """Return the record of the re-ruling, with the audit status of each row."""
    with tempfile.TemporaryDirectory() as tmp:
        tree = AUDIT.test_tree(TARGET.commit, Path(tmp))
        _, gated, notes = AUDIT.run_audit(tree, TARGET)
    status = {row.req_id: (s, n) for (row, s, *_), n in zip(gated, notes, strict=True)}
    lines = [
        "Prepared by: Agent 4 - Independent Verificator - model: claude-opus-5-5",
        "",
        "# V3-01 for release 0.0.4: the rows whose tests changed since 0.0.2 (U-V18, generated)",
        "",
        "Generated by `python3 tests/independent/m7/v18_rerule.py --write`. Do not edit by hand; the rulings live in",
        "`tests/independent/m7/v3_01_rulings_v18.py`. Ruling words as in `V3-01.md`: `checks` is the V3-01 verdict",
        "`verified` (every clause of the acceptance is asserted by a cited test, gate or record that passed in the",
        "0.0.4 run), `partial` names the missing piece. Audit status: the row's status in",
        "`docs/phase3/verification/req_audit.md` (`req_audit.py --target 0.0.4`), which also needs a test that names",
        "every planned test ID of the row and keeps rows that need Windows or FEA `partial`.",
        "",
        "Rows: the live must rows with a test file changed between 0a74974 and c25d8a9 that carries their marker",
        "(`python3 tests/independent/m7/v18_changed_rows.py --report <main> --report <latency>`; the lines of the 18",
        "changed test files that carry no must marker are left out):",
        "",
        "```",
        changed_rows.rstrip(),
        "```",
        "",
        "| REQ | Ruling | Audit status | Tests cited | Reason | Missing (kind, owner) |",
        "|---|---|---|---|---|---|",
    ]
    for req, r in sorted(V18.RULINGS.items()):
        cites = "<br>".join(f"`{c}`" for c in r.cites) or "-"
        missing = f"{r.missing} ({r.kind}, {r.owner})" if r.missing else "-"
        lines.append(f"| {req} | {r.ruling} | {status[req][0]} | {cites} | {r.reason} | {missing} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Pin, check or write, as the flags say."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--pin", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--changed-rows", type=Path, help="saved output of v18_changed_rows.py for --write")
    args = parser.parse_args(argv)
    if args.pin:
        with tempfile.TemporaryDirectory() as tmp:
            pinned = pins(AUDIT.test_tree(TARGET.commit, Path(tmp)))
        V18.PIN_FILE.write_text(json.dumps(pinned, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        missing = [f"{req} {c}" for req, cs in pinned.items() for c, h in cs.items() if h == "missing"]
        print(f"wrote {V18.PIN_FILE.relative_to(REPO)}: {sum(len(c) for c in pinned.values())} pins, missing {missing}")
    if args.check:
        found = problems()
        print(*found, sep="\n")
        print(f"{len(found)} problems over {sum(len(r.cites) for r in V18.RULINGS.values())} cites")
        if found:
            return 1
    if args.write:
        RECORD.write_text(render(args.changed_rows.read_text(encoding="utf-8")), encoding="utf-8")
        print(f"wrote {RECORD.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
