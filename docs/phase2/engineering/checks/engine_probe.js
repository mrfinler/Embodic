// Prepared by: Agent 2 — Motor Design Expert — model: claude-opus-5-5
// Probes the read-only Xcoil engine for the facts the serpentine/wave port gate relies on.
// Run: node docs/phase2/engineering/checks/engine_probe.js
'use strict';
const E = require('/home/claude/serpentine/src/engine.js');

const out = {};
// 1. star of slots: Xcoil floating-point belts vs the exact integer rule (spiral_reference.py)
out.starOfSlots = [[12, 5], [12, 7], [12, 8], [18, 8], [24, 7], [24, 11], [24, 13]].map(([Q, pp]) => {
  const s = E.starOfSlots(Q, pp, 3);
  const pat = s.coils.map(c => (c.sign > 0 ? 'ABC' : 'abc')[c.phase]).join('');
  return { Q, poles: 2 * pp, ok: s.ok, pattern: pat };
});
// 2. 1-D field limit: fieldHarmonic at a very large radius vs the magnetic-circuit value
const F = { pp: 1, Br: 1.3, muR: 1.05, lm: 3.0, alphaP: 0.85, G: 1.1 };
const b1 = E.fieldHarmonic(1, 1e5, 0, F).Bz;
const b1d = 4 / Math.PI * Math.sin(Math.PI * F.alphaP / 2) * F.Br * F.lm / (F.lm + F.muR * F.G);
out.field1D = { engine: b1, closedForm: b1d, rel: (b1 - b1d) / b1d };
// 3. copper constants and track resistance (Xcoil constants: rho20 = 1.724e-8)
out.traceResistance = { R20: E.traceResistance(1000, 0.5, 0.0348, 20), R60: E.traceResistance(1000, 0.5, 0.0348, 60) };
out.viaBarrelArea = E.viaBarrelArea(0.3, 0.025);
out.skinDepthMm_133Hz_20C = E.skinDepthMm(400 / 3, 20);
out.ipc2221 = { external: E.ipc2221Current(0.5 * 0.0348, 20, false), internal: E.ipc2221Current(0.5 * 0.0348, 20, true) };
out.inverterVoltage = ['svpwm', 'sine', 'sixstep'].map(m => ({ mode: m, star: E.inverterVoltage({ vDc: 24, modulation: m }, 'star') }));
// 4. full default runs of the two ported topologies (golden fixtures are generated by Agent 3/4; this only shows that they run)
const runs = {};
for (const [name, extra] of [['serpentine', { topology: 'serpentine' }], ['wave-involute', { topology: 'wave', waveStyle: 'involute', turns: 2 }],
  ['wave-overlap', { topology: 'wave', waveStyle: 'overlap', turns: 2 }]]) {
  const r = E.compute(Object.assign({}, E.DEFAULTS, extra));
  const a = r.analysis || {};
  runs[name] = { ok: r.ok, errors: (r.errors || []).map(e => e.code), Ke1: a.Ke1, Rphase: a.Rphase, rLineLine: a.rLineLine, pEddy: a.pEddy,
    pCirc: a.pCirc, Ls: a.inductance && a.inductance.Ls, drcTrace: r.drc && r.drc.traceClearance };
}
out.defaultRuns = runs;
// 5. DRC slack: the literal 0.004 mm tolerance in the engine source
const src = require('fs').readFileSync('/home/claude/serpentine/src/engine.js', 'utf8').split('\n');
out.drcSlackLines = src.map((l, i) => [i + 1, l]).filter(([, l]) => /tol = 0\.004/.test(l)).map(([n]) => n);
console.log(JSON.stringify(out, null, 1));
