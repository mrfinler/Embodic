"""Consistency checks for the Phase 2 architecture contract (unit U-S1).

Run from anywhere:
    python3 docs/phase2/architecture/checks/check_contract.py          # check only
    python3 docs/phase2/architecture/checks/check_contract.py --write  # regenerate the matrix in test_plan.md, then check

Exit code 0 when every check passes, 1 otherwise.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
import types
from pathlib import Path

ARCH = Path(__file__).resolve().parents[1]
REPO = ARCH.parents[2]
PHASE1_REQS = REPO / "docs/phase1/architecture/requirements_draft.md"
PHASE1_TESTS = REPO / "docs/phase1/architecture/test_plan_draft.md"

REQUIREMENTS = ARCH / "requirements.md"
INTERFACES = ARCH / "interfaces.md"
TEST_PLAN = ARCH / "test_plan.md"
WORK = ARCH / "work_breakdown.md"
LAYOUT = ARCH / "package_layout.md"
ADR_DIR = ARCH / "decisions"
REQUIRED_ADRS = ("ADR-0004", "ADR-0005", "ADR-0010", "ADR-0011", "ADR-0012")

MODEL_LINE = re.compile(r"Prepared by: Agent 6 .* model: claude-opus-5-5")
THAI = re.compile("[" + chr(0x0E00) + "-" + chr(0x0E7F) + "]")
REQ_ID = re.compile(r"REQ-[FNKTL]-\d{2}")
TEST_ID = re.compile(r"\b(?:UT-[A-Z]{2,3}-\d{2}|(?:GR|OR|PR|BV|UI|KX|KS|LG|AX|PF|MT|PK|TR|IT)-\d{2})\b")
DISPOSITIONS = {"carried", "amended", "withdrawn", "new"}
PRIORITIES = {"must", "should", "could", "-"}
MILESTONES = {"M1", "M2", "M3", "M4", "M5", "-"}
MATRIX_START = "<!-- matrix:start (generated by checks/check_contract.py --write; do not edit by hand) -->"
MATRIX_END = "<!-- matrix:end -->"


def table_rows(text: str) -> list[list[str]]:
    rows = []
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("|") and s.endswith("|") and not re.match(r"^\|[\s:|-]+\|$", s):
            rows.append([c.strip() for c in s.strip("|").split("|")])
    return rows


def parse_requirements() -> list[dict[str, str]]:
    reqs = []
    for cells in table_rows(REQUIREMENTS.read_text(encoding="utf-8")):
        if not REQ_ID.fullmatch(cells[0]):
            continue
        if len(cells) != 9:
            raise SystemExit(f"{cells[0]}: expected 9 columns, found {len(cells)}")
        keys = ("id", "disposition", "statement", "rationale", "priority", "acceptance", "milestone", "owner", "tests")
        reqs.append(dict(zip(keys, cells)))
    return reqs


def defined_test_ids() -> tuple[set[str], set[str]]:
    """Return (defined, withdrawn). A test is defined when it heads a table row in either plan."""
    phase1 = {c[0] for c in table_rows(PHASE1_TESTS.read_text(encoding="utf-8")) if TEST_ID.fullmatch(c[0])}
    plan = TEST_PLAN.read_text(encoding="utf-8")
    phase2 = {c[0] for c in table_rows(plan) if TEST_ID.fullmatch(c[0])}
    withdrawn_block = re.search(r"<!-- withdrawn-tests:start -->(.*?)<!-- withdrawn-tests:end -->", plan, re.S)
    withdrawn = set(TEST_ID.findall(withdrawn_block.group(1))) if withdrawn_block else set()
    return (phase1 | phase2), withdrawn


def check_requirements(errors: list[str]) -> list[dict[str, str]]:
    reqs = parse_requirements()
    ids = [r["id"] for r in reqs]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        errors.append(f"duplicate REQ IDs: {dupes}")
    phase1_ids = {c[0] for c in table_rows(PHASE1_REQS.read_text(encoding="utf-8")) if REQ_ID.fullmatch(c[0])}
    missing = sorted(phase1_ids - set(ids))
    if missing:
        errors.append(f"Phase 1 REQs neither carried, amended nor withdrawn: {missing}")
    defined, withdrawn = defined_test_ids()
    for r in reqs:
        if r["disposition"] not in DISPOSITIONS:
            errors.append(f"{r['id']}: disposition {r['disposition']!r}")
        if r["disposition"] == "new" and r["id"] in phase1_ids:
            errors.append(f"{r['id']}: marked new but exists in Phase 1")
        if r["disposition"] != "new" and r["id"] not in phase1_ids:
            errors.append(f"{r['id']}: marked {r['disposition']} but absent from Phase 1")
        if r["priority"] not in PRIORITIES:
            errors.append(f"{r['id']}: priority {r['priority']!r}")
        if r["milestone"] not in MILESTONES:
            errors.append(f"{r['id']}: milestone {r['milestone']!r}")
        live = r["disposition"] != "withdrawn"
        if live and (r["milestone"] == "-" or r["priority"] == "-" or not r["owner"].startswith(("embodic", "tools", "resources", "docs", "pyproject", "tests"))):
            errors.append(f"{r['id']}: live REQ needs milestone, priority and owner module")
        if not r["statement"] or (live and " shall " not in f" {r['statement']} " and " should " not in f" {r['statement']} " and " could " not in f" {r['statement']} "):
            errors.append(f"{r['id']}: statement lacks shall/should/could")
        if live and not r["acceptance"]:
            errors.append(f"{r['id']}: no acceptance criterion")
        tests = TEST_ID.findall(r["tests"])
        if not tests:
            errors.append(f"{r['id']}: no test ID")
        for t in tests:
            if t not in defined:
                errors.append(f"{r['id']}: test {t} is not defined in either test plan")
            elif t in withdrawn and live:
                errors.append(f"{r['id']}: live REQ points at withdrawn test {t}")
    return reqs


def render_matrix(reqs: list[dict[str, str]]) -> str:
    lines = [MATRIX_START, "", "| REQ | Disp. | Prio | M | Owner module | Tests |", "|---|---|---|---|---|---|"]
    for r in sorted(reqs, key=lambda r: (r["id"][4], int(r["id"][6:]))):
        lines.append(f"| {r['id']} | {r['disposition']} | {r['priority']} | {r['milestone']} | {r['owner']} | {', '.join(TEST_ID.findall(r['tests']))} |")
    lines += ["", MATRIX_END]
    return "\n".join(lines)


def check_matrix(reqs: list[dict[str, str]], write: bool, errors: list[str]) -> None:
    plan = TEST_PLAN.read_text(encoding="utf-8")
    block = re.search(re.escape(MATRIX_START) + r".*?" + re.escape(MATRIX_END), plan, re.S)
    if not block:
        errors.append("test_plan.md has no generated matrix block")
        return
    fresh = render_matrix(reqs)
    if write and block.group(0) != fresh:
        TEST_PLAN.write_text(plan.replace(block.group(0), fresh), encoding="utf-8")
    elif block.group(0) != fresh:
        errors.append("test_plan.md matrix is stale; run with --write")


def check_interfaces(errors: list[str]) -> int:
    blocks = re.findall(r"```python\n(.*?)```", INTERFACES.read_text(encoding="utf-8"), re.S)
    if not blocks:
        errors.append("interfaces.md has no python blocks")
    for i, src in enumerate(blocks, 1):
        try:
            ast.parse(src)
        except SyntaxError as exc:
            errors.append(f"interfaces.md block {i}: {exc}")
    module = types.ModuleType("embodic_contract_stub")
    sys.modules[module.__name__] = module  # dataclasses resolve string annotations through sys.modules
    try:
        exec(compile("\n".join(blocks), "interfaces.md", "exec"), module.__dict__)
    except Exception as exc:  # noqa: BLE001 - any failure while defining the stubs is a contract defect
        errors.append(f"interfaces.md blocks fail when executed in order: {type(exc).__name__}: {exc}")
    return len(blocks)


def parse_units() -> list[dict[str, object]]:
    units = []
    for cells in table_rows(WORK.read_text(encoding="utf-8")):
        if not re.fullmatch(r"U-(M\d[a-z]|V\d|F\d)", cells[0]):
            continue
        if len(cells) != 11:
            raise SystemExit(f"{cells[0]}: expected 11 columns, found {len(cells)}")
        unit_id, milestone, _owner, _goal, _inputs, _outputs, paths, verify, done, size, deps = cells
        if not (verify and done and size):
            raise SystemExit(f"{unit_id}: verify command, done predicate and size are required")
        units.append({
            "id": unit_id,
            "milestone": milestone,
            "paths": [p.strip().strip("`") for p in paths.split("<br>") if p.strip()],
            "deps": [d for d in re.findall(r"U-(?:M\d[a-z]|V\d|F\d)", deps)],
        })
    return units


def paths_overlap(a: str, b: str) -> bool:
    def norm(p: str) -> tuple[str, bool]:
        return (p[:-3], True) if p.endswith("/**") else (p, False)
    (pa, da), (pb, db) = norm(a), norm(b)
    if pa == pb:
        return True
    return (da and pb.startswith(pa + "/")) or (db and pa.startswith(pb + "/"))


def check_work(errors: list[str]) -> list[dict[str, object]]:
    units = parse_units()
    by_id = {u["id"]: u for u in units}
    for u in units:
        for d in u["deps"]:
            if d not in by_id:
                errors.append(f"{u['id']}: unknown dependency {d}")
        if not u["paths"]:
            errors.append(f"{u['id']}: no write paths")

    ancestors: dict[str, set[str]] = {}

    def walk(uid: str, seen: tuple[str, ...] = ()) -> set[str]:
        if uid in seen:
            errors.append(f"dependency cycle through {uid}")
            return set()
        if uid not in ancestors:
            acc: set[str] = set()
            for d in by_id[uid]["deps"]:
                if d in by_id:
                    acc |= {d} | walk(d, seen + (uid,))
            ancestors[uid] = acc
        return ancestors[uid]

    for u in units:
        walk(u["id"])
    for i, a in enumerate(units):
        for b in units[i + 1:]:
            ordered = a["id"] in ancestors[b["id"]] or b["id"] in ancestors[a["id"]]
            for pa in a["paths"]:
                for pb in b["paths"]:
                    if paths_overlap(pa, pb) and not ordered:
                        errors.append(f"concurrent units {a['id']} and {b['id']} share write path {pa} ~ {pb}")
    for m in sorted({u["milestone"] for u in units}):
        same = [u for u in units if u["milestone"] == m]
        for i, a in enumerate(same):
            for b in same[i + 1:]:
                for pa in a["paths"]:
                    for pb in b["paths"]:
                        if paths_overlap(pa, pb):
                            errors.append(f"milestone {m}: {a['id']} and {b['id']} share {pa} ~ {pb}")
    return units


def section(text: str, number: int) -> str:
    match = re.search(rf"^## {number}\. .*?(?=^## |\Z)", text, re.S | re.M)
    return match.group(0) if match else ""


def check_batches(units: list[dict[str, object]], errors: list[str]) -> tuple[int, int]:
    """work_breakdown.md section 8 (U-D3): units of one batch, plus the section 1 units of the wave a batch is named
    after (section 3), run at the same time and must not share a write path."""
    text = WORK.read_text(encoding="utf-8")
    waves = {c[0]: re.findall(r"U-(?:M\d[a-z]|V\d|F\d)\b", c[1]) for c in table_rows(section(text, 3)) if re.fullmatch(r"W\d+", c[0])}
    paths_of = {str(u["id"]): u["paths"] for u in units}
    rows = [c for c in table_rows(section(text, 8)) if c[0].startswith("U-")]
    batches: dict[str, list[tuple[str, list[str]]]] = {}
    for cells in rows:
        if len(cells) != 7:
            raise SystemExit(f"section 8 row {cells[0]}: expected 7 columns, found {len(cells)}")
        unit_id, _owner, batch, paths = cells[0], cells[1], cells[2], cells[3]
        batches.setdefault(batch, []).append((unit_id, [p.strip().strip("`") for p in paths.split("<br>") if p.strip()]))
    ids = [r[0] for r in rows]
    for dupe in sorted({i for i in ids if ids.count(i) > 1}):
        errors.append(f"section 8: unit {dupe} listed twice")
    for batch, members in batches.items():
        group = members + [(u, paths_of[u]) for u in waves.get(batch, []) if u in paths_of]  # type: ignore[misc]
        for i, (a, pa_list) in enumerate(group):
            for b, pb_list in group[i + 1:]:
                for pa in pa_list:
                    for pb in pb_list:
                        if paths_overlap(pa, pb):
                            errors.append(f"batch {batch}: {a} and {b} share write path {pa} ~ {pb}")
    return len(rows), len(batches)


TEST_LEVELS = ("unit", "golden", "ui")
NON_PACKAGE_FOLDERS = {"data", "expected_diffs"}


def check_test_packages(units: list[dict[str, object]], errors: list[str]) -> int:
    """package_layout.md section 1 naming rule on planned write paths: the folder right under tests/<level>/ becomes a
    top-level module name (MT-08), so it must be unique across levels and must not be a standard-library name."""
    levels_by_name: dict[str, set[str]] = {}
    for u in units:
        for path in u["paths"]:  # type: ignore[attr-defined]
            parts = path.split("/")
            if len(parts) < 3 or parts[0] != "tests" or parts[1] not in TEST_LEVELS:
                continue
            name = parts[2]
            if name in NON_PACKAGE_FOLDERS or "." in name or name == "**":
                continue
            levels_by_name.setdefault(name, set()).add(parts[1])
    for name, levels in sorted(levels_by_name.items()):
        if len(levels) > 1:
            errors.append(f"test package name {name!r} is planned under {sorted(levels)}; top-level names must be unique")
        if name in sys.stdlib_module_names:
            errors.append(f"test package name {name!r} shadows the standard-library module {name!r}")
    return len(levels_by_name)


def check_files(errors: list[str]) -> list[Path]:
    files = sorted(p for p in ARCH.rglob("*") if p.is_file() and p.suffix in {".md", ".py", ".toml", ".json"})
    for p in files:
        text = p.read_text(encoding="utf-8")
        first = text.splitlines()[0] if text else ""
        if not MODEL_LINE.search(first):
            errors.append(f"{p.relative_to(ARCH)}: first line is not the 'Prepared by' model line")
        if THAI.search(text):
            errors.append(f"{p.relative_to(ARCH)}: contains Thai characters")
        if chr(0x2014) in text or chr(0x2013) in text:
            errors.append(f"{p.relative_to(ARCH)}: contains a long dash (em or en)")
    for adr in REQUIRED_ADRS:
        if not list(ADR_DIR.glob(f"{adr}-*.md")):
            errors.append(f"missing {adr} in decisions/")
    for required in (REQUIREMENTS, INTERFACES, TEST_PLAN, WORK, LAYOUT):
        if not required.exists():
            errors.append(f"missing {required.name}")
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="regenerate the requirements-to-tests matrix in test_plan.md")
    args = parser.parse_args()
    errors: list[str] = []
    files = check_files(errors)
    reqs = check_requirements(errors) if REQUIREMENTS.exists() and TEST_PLAN.exists() else []
    if reqs:
        check_matrix(reqs, args.write, errors)
    blocks = check_interfaces(errors) if INTERFACES.exists() else 0
    units = check_work(errors) if WORK.exists() else []
    test_packages = check_test_packages(units, errors)
    batch_rows, batch_count = check_batches(units, errors) if WORK.exists() else (0, 0)
    live = [r for r in reqs if r["disposition"] != "withdrawn"]
    print(f"files checked: {len(files)}")
    print(f"requirements: {len(reqs)} total, {len(live)} live, {len(reqs) - len(live)} withdrawn; "
          f"by disposition: { {d: sum(r['disposition'] == d for r in reqs) for d in sorted(DISPOSITIONS)} }")
    print(f"interfaces.md python blocks: {blocks} (ast.parse each, then exec in order)")
    print(f"work units: {len(units)}; milestones: {sorted({str(u['milestone']) for u in units})}")
    print(f"planned top-level test packages: {test_packages}")
    print(f"section 8 units: {batch_rows} in {batch_count} batches")
    if errors:
        print(f"FAIL: {len(errors)} problem(s)")
        for e in errors:
            print(f"  - {e}")
        return 1
    print("PASS: REQ IDs unique; every REQ has >= 1 defined test ID; Phase 1 REQs all dispositioned; "
          "matrix current; interfaces parse and execute; concurrent and same-milestone write paths disjoint; "
          "section 8 batch write paths disjoint; "
          "planned test package names unique and not stdlib; model line first; no Thai; no long dashes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
